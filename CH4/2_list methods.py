l1 =[4,5,8,2,9,10,12,15]

l1.append(16) # Adds 16 at the end of the list
l1.insert(0, 4) # Adds 4 at the beginning of the list
l1.remove(10) # Removes 10 from the list
l1.pop(3) # Removes the element at index 3 from the list
l1.sort() # Sorts the list in ascending order
l1.reverse() # Reverses the list 
print(l1)